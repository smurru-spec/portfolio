/* ---------- lingua attiva: ?lang=en  >  scelta salvata  >  italiano ---------- */
const LANG = (()=>{
  const q = new URLSearchParams(location.search).get("lang");
  if(q==="it"||q==="en"){ try{localStorage.setItem("sm-lang",q)}catch(e){} return q; }
  try{ const s=localStorage.getItem("sm-lang"); if(s==="it"||s==="en") return s; }catch(e){}
  return "it";
})();
document.documentElement.lang = LANG;

/* t("chiave") -> testo nella lingua attiva */
const t = k => (T[LANG] && T[LANG][k]) ?? T.it[k] ?? k;
/* L(valore) -> se il valore è {it:..., en:...} restituisce la lingua giusta */
const L = v => (v && typeof v==="object" && !Array.isArray(v) && ("it" in v || "en" in v)) ? (v[LANG] ?? v.it) : v;

/* applica i testi agli elementi con data-i18n / data-i18n-ph / data-i18n-aria */
function applyI18n(root=document){
  root.querySelectorAll("[data-i18n]").forEach(el=>el.innerHTML=t(el.dataset.i18n));
  root.querySelectorAll("[data-i18n-ph]").forEach(el=>el.placeholder=t(el.dataset.i18nPh));
  root.querySelectorAll("[data-i18n-aria]").forEach(el=>el.setAttribute("aria-label",t(el.dataset.i18nAria)));
}

